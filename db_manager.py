def add_pretest_change(
    project_name,
    run_id,
    tier,
    changes,
    change_date,
):
    """
    Add a new pretest change.

    Duplicate Run IDs are allowed.

    Returns:
        (True, False) -> successfully inserted, not duplicate
        (True, True)  -> successfully inserted, duplicate Run ID detected
        (False, None) -> failed
    """

    try:

        if not all(
            [
                project_name,
                run_id,
                tier,
                changes,
                change_date,
            ]
        ):

            print(
                "❌ All fields are required for pretest change"
            )

            return False, None

        project_name = str(project_name).strip()
        run_id = str(run_id).strip()
        tier = str(tier).strip()
        changes = str(changes).strip()
        change_date = str(change_date).strip()

        with _connection() as conn:

            try:

                # -------------------------------------------------------------
                # Find project
                # -------------------------------------------------------------

                project = conn.execute(
                    _prepare_sql(
                        """
                        SELECT project_id
                        FROM projects
                        WHERE project_name = ?
                        """
                    ),
                    (project_name,),
                ).fetchone()

                if not project:

                    print(
                        f"❌ Project '{project_name}' not found"
                    )

                    return False, None

                project_id = project[0]

                # -------------------------------------------------------------
                # Check duplicate Run ID
                # -------------------------------------------------------------

                is_duplicate = (
                    conn.execute(
                        _prepare_sql(
                            """
                            SELECT 1
                            FROM pretest_changes
                            WHERE project_id = ?
                              AND run_id = ?
                            LIMIT 1
                            """
                        ),
                        (
                            project_id,
                            run_id,
                        ),
                    ).fetchone()
                    is not None
                )

                # -------------------------------------------------------------
                # Insert record
                # -------------------------------------------------------------

                conn.execute(
                    _prepare_sql(
                        """
                        INSERT INTO pretest_changes (
                            project_id,
                            run_id,
                            tier,
                            changes,
                            change_date
                        )
                        VALUES (?, ?, ?, ?, ?)
                        """
                    ),
                    (
                        project_id,
                        run_id,
                        tier,
                        changes,
                        change_date,
                    ),
                )

                conn.commit()

                return True, is_duplicate

            except Exception as exc:

                conn.rollback()

                print(
                    f"❌ Database error adding pretest change: {exc}"
                )

                return False, None

    except Exception as exc:

        print(
            f"❌ Unexpected error in add_pretest_change: {exc}"
        )

        return False, None


def update_pretest_change(
    project_name,
    run_id,
    tier,
    changes,
    change_date,
):
    """
    Update an existing pretest change identified by project and Run ID.
    """

    try:

        if not all(
            [
                project_name,
                run_id,
                tier,
                changes,
                change_date,
            ]
        ):

            print(
                "❌ All fields are required for updating pretest change"
            )

            return False

        project_name = str(project_name).strip()
        run_id = str(run_id).strip()
        tier = str(tier).strip()
        changes = str(changes).strip()
        change_date = str(change_date).strip()

        with _connection() as conn:

            try:

                cursor = conn.execute(
                    _prepare_sql(
                        """
                        UPDATE pretest_changes
                        SET
                            tier = ?,
                            changes = ?,
                            change_date = ?
                        WHERE project_id = (
                            SELECT project_id
                            FROM projects
                            WHERE project_name = ?
                        )
                        AND run_id = ?
                        """
                    ),
                    (
                        tier,
                        changes,
                        change_date,
                        project_name,
                        run_id,
                    ),
                )

                conn.commit()

                return cursor.rowcount > 0

            except Exception as exc:

                conn.rollback()

                print(
                    f"❌ Database error updating pretest change: {exc}"
                )

                return False

    except Exception as exc:

        print(
            f"❌ Unexpected error in update_pretest_change: {exc}"
        )

        return False


# =============================================================================
# DATE HELPERS
# =============================================================================

def _parse_change_date(date_value):
    """
    Return a comparable date value for pretest-change records.
    """

    if date_value is None:
        return datetime.min.date()

    date_str = str(date_value).strip()

    if not date_str:
        return datetime.min.date()

    formats = (
        "%Y-%m-%d",
        "%Y-%m-%d %H:%M:%S",
        "%d-%m-%Y",
        "%d-%m-%Y %H:%M:%S",
    )

    for fmt in formats:

        try:
            return datetime.strptime(
                date_str,
                fmt,
            ).date()

        except ValueError:
            continue

    try:

        return datetime.fromisoformat(
            date_str
        ).date()

    except ValueError:

        return datetime.min.date()


