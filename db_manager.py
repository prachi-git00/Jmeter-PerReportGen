# READ PRETEST CHANGES
# =============================================================================

def get_pretest_changes(project_name):
    """
    Get all pretest changes for a project,
    sorted newest first.
    """

    return get_pretest_changes_filtered(
        project_name
    )


def get_pretest_changes_filtered(
    project_name,
    run_id=None,
    tier=None,
    start_date=None,
    end_date=None,
):
    """
    Get pretest changes for a project filtered by:

        - Run ID
        - Tier
        - Start date
        - End date

    Results are sorted newest date first.
    """

    try:

        if not project_name:
            return []

        query = """
            SELECT
                run_id,
                tier,
                changes,
                change_date
            FROM pretest_changes
            WHERE project_id = (
                SELECT project_id
                FROM projects
                WHERE project_name = ?
            )
        """

        params = [
            project_name
        ]

        # ---------------------------------------------------------------------
        # Run ID filter
        # ---------------------------------------------------------------------

        if run_id:

            query += """
                AND run_id LIKE ?
            """

            params.append(
                f"%{str(run_id).strip()}%"
            )

        # ---------------------------------------------------------------------
        # Tier filter
        # ---------------------------------------------------------------------

        if tier:

            query += """
                AND tier LIKE ?
            """

            params.append(
                f"%{str(tier).strip()}%"
            )

        # ---------------------------------------------------------------------
        # Start date
        # ---------------------------------------------------------------------

        if start_date:

            query += """
                AND change_date >= ?
            """

            params.append(
                str(start_date)
            )

        # ---------------------------------------------------------------------
        # End date
        # ---------------------------------------------------------------------

        if end_date:

            query += """
                AND change_date <= ?
            """

            params.append(
                str(end_date)
            )

        # ---------------------------------------------------------------------
        # IMPORTANT:
        #
        # Do NOT use:
        #
        #     ORDER BY date(change_date)
        #
        # because that is SQLite-specific.
        #
        # change_date is already DATE, so direct ordering works in both
        # PostgreSQL and SQLite.
        # ---------------------------------------------------------------------

        query += """
            ORDER BY
                change_date DESC,
                created_timestamp DESC
        """

        with _connection() as conn:

            cursor = conn.execute(
                _prepare_sql(query),
                tuple(params),
            )

            return cursor.fetchall()

    except Exception as exc:

        print(
            f"❌ Error retrieving pretest changes: {exc}"
        )

        return []


