import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime


# =============================================================================
# DATABASE CONFIGURATION
# =============================================================================

DB_FILE = os.environ.get("DB_FILE", "pretest_changes.db")

# Support either DATABASE_URL or POSTGRES_URL.
DATABASE_URL = (
    os.environ.get("DATABASE_URL")
    or os.environ.get("POSTGRES_URL")
)

# Optional explicit database type.
# Examples:
#   DB_TYPE=sqlite
#   DB_TYPE=postgres
#   DB_TYPE=postgresql
DB_TYPE = os.environ.get("DB_TYPE", "").strip().lower()


# =============================================================================
# DATABASE TYPE
# =============================================================================

def _is_postgres_enabled():
    """
    Determine whether PostgreSQL should be used.

    PostgreSQL is enabled when:
      - DB_TYPE is postgres/postgresql, OR
      - DATABASE_URL/POSTGRES_URL is configured.

    Otherwise SQLite is used.
    """
    return (
        DB_TYPE in {"postgres", "postgresql"}
        or bool(DATABASE_URL)
    )


def _database_name():
    """Return a friendly database name for error messages."""
    return "PostgreSQL" if _is_postgres_enabled() else "SQLite"


def _prepare_sql(sql):
    """
    Convert SQLite-style '?' placeholders to PostgreSQL '%s' placeholders.

    The application uses '?' throughout its SQL so the same queries can work
    with both database engines.
    """
    if _is_postgres_enabled():
        return sql.replace("?", "%s")

    return sql


def _primary_key_sql():
    """
    Return a database-specific auto-increment primary key definition.
    """
    if _is_postgres_enabled():
        return "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

    return "INTEGER PRIMARY KEY AUTOINCREMENT"


# =============================================================================
# CONNECTION MANAGEMENT
# =============================================================================

@contextmanager
def _connection():
    """
    Open a database connection.

    PostgreSQL:
        Uses psycopg first, then psycopg2.

    SQLite:
        Uses the local DB_FILE.

    Important:
        PostgreSQL connection failures are NOT silently converted to SQLite.
        This prevents deployment configuration errors from being hidden.
    """

    if _is_postgres_enabled():

        if not DATABASE_URL:
            raise RuntimeError(
                "PostgreSQL is enabled but DATABASE_URL is not configured. "
                "Set DATABASE_URL in your Streamlit deployment secrets."
            )

        conn = None

        # ---------------------------------------------------------------------
        # Try psycopg 3
        # ---------------------------------------------------------------------
        try:
            import psycopg

            conn = psycopg.connect(
                DATABASE_URL,
                connect_timeout=10,
            )

        except ModuleNotFoundError:

            # -------------------------------------------------------------
            # Try psycopg2
            # -------------------------------------------------------------
            try:
                import psycopg2

                conn = psycopg2.connect(
                    DATABASE_URL,
                    connect_timeout=10,
                )

            except ModuleNotFoundError as exc:
                raise RuntimeError(
                    "PostgreSQL is configured but no PostgreSQL driver is "
                    "installed. Add 'psycopg[binary]' or 'psycopg2-binary' "
                    "to requirements.txt."
                ) from exc

            except Exception as exc:
                raise RuntimeError(
                    f"PostgreSQL connection failed: {exc}"
                ) from exc

        except Exception as exc:
            raise RuntimeError(
                f"PostgreSQL connection failed: {exc}"
            ) from exc

        try:
            yield conn
        finally:
            try:
                conn.close()
            except Exception:
                pass

        return

    # =========================================================================
    # SQLITE
    # =========================================================================

    conn = sqlite3.connect(
        DB_FILE,
        timeout=10.0,
    )

    try:
        # Enable foreign-key enforcement for SQLite.
        conn.execute("PRAGMA foreign_keys = ON")

        yield conn

    finally:
        try:
            conn.close()
        except Exception:
            pass


# =============================================================================
# DATABASE METADATA HELPERS
# =============================================================================

def _table_columns(conn):
    """
    Return column names for pretest_changes.

    Works with both SQLite and PostgreSQL.
    """

    if _is_postgres_enabled():

        cursor = conn.cursor()

        cursor.execute(
            """
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = %s
            ORDER BY ordinal_position
            """,
            ("pretest_changes",),
        )

        return [row[0] for row in cursor.fetchall()]

    # SQLite
    cursor = conn.cursor()

    cursor.execute(
        "PRAGMA table_info(pretest_changes)"
    )

    return [row[1] for row in cursor.fetchall()]


def _duplicate_error(exc):
    """
    Detect duplicate/unique constraint errors across SQLite and PostgreSQL.
    """

    message = str(exc).lower()

    return (
        "integrity" in message
        or "duplicate key" in message
        or "unique constraint" in message
        or "already exists" in message
        or "uniqueviolation" in message
    )


