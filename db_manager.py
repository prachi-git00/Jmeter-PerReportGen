def get_all_projects():
    """
    Get all project names sorted alphabetically.
    """

    try:

        with _connection() as conn:

            cursor = conn.execute(
                _prepare_sql(
                    """
                    SELECT project_name
                    FROM projects
                    ORDER BY project_name
                    """
                )
            )

            return [
                row[0]
                for row in cursor.fetchall()
            ]

    except Exception as exc:

        print(
            f"❌ Error retrieving projects: {exc}"
        )

        return []


def create_project(project_name):
    """
    Create a new project.

    Returns:
        True  -> project created
        False -> project already exists or creation failed
    """

    try:

        if not project_name or not project_name.strip():

            print(
                "❌ Project name cannot be empty"
            )

            return False

        project_name = project_name.strip()

        with _connection() as conn:

            try:

                conn.execute(
                    _prepare_sql(
                        """
                        INSERT INTO projects (project_name)
                        VALUES (?)
                        """
                    ),
                    (project_name,),
                )

                conn.commit()

                return True

            except Exception as exc:

                conn.rollback()

                if _duplicate_error(exc):

                    print(
                        f"❌ Project '{project_name}' already exists"
                    )

                    return False

                print(
                    f"❌ Database error creating project: {exc}"
                )

                return False

    except Exception as exc:

        print(
            f"❌ Unexpected error in create_project: {exc}"
        )

        return False


def get_project_id(project_name):
    """
    Get project ID by project name.
    """

    if not project_name:
        return None

    try:

        with _connection() as conn:

            result = conn.execute(
                _prepare_sql(
                    """
                    SELECT project_id
                    FROM projects
                    WHERE project_name = ?
                    """
                ),
                (project_name,),
            ).fetchone()

            return result[0] if result else None

    except Exception as exc:

        print(
            f"❌ Error retrieving project ID: {exc}"
        )

        return None


