# DATAFRAME VERSION
# =============================================================================

def get_pretest_changes_as_dataframe(project_name):
    """
    Get pretest changes as a pandas DataFrame.
    """

    import pandas as pd

    changes = get_pretest_changes(
        project_name
    )

    if not changes:

        return pd.DataFrame(
            columns=[
                "Sr. No.",
                "Run ID",
                "Tier",
                "Changes Done",
                "Date",
            ]
        )

    data = []

    for idx, (
        run_id,
        tier,
        changes_text,
        change_date,
    ) in enumerate(
        changes,
        1,
    ):

        data.append(
            {
                "Sr. No.": idx,
                "Run ID": run_id,
                "Tier": tier,
                "Changes Done": changes_text,
                "Date": change_date,
            }
        )

    return pd.DataFrame(data)


# =============================================================================
# DELETE PRETEST CHANGE
# =============================================================================

def delete_pretest_change(
    project_name,
    run_id,
):
    """
    Delete a pretest change by project and Run ID.

    If duplicate Run IDs exist within the same project,
    all matching records are deleted, preserving the behavior
    of the original application.
    """

    try:

        if not project_name or not run_id:
            return False

        with _connection() as conn:

            try:

                cursor = conn.execute(
                    _prepare_sql(
                        """
                        DELETE FROM pretest_changes
                        WHERE project_id = (
                            SELECT project_id
                            FROM projects
                            WHERE project_name = ?
                        )
                        AND run_id = ?
                        """
                    ),
                    (
                        project_name,
                        run_id,
                    ),
                )

                conn.commit()

                return cursor.rowcount > 0

            except Exception as exc:

                conn.rollback()

                print(
                    f"❌ Database error deleting pretest change: {exc}"
                )

                return False

    except Exception as exc:

        print(
            f"❌ Unexpected error in delete_pretest_change: {exc}"
        )

        return False


# =============================================================================
# DELETE PROJECT
# =============================================================================

def delete_project(project_name):
    """
    Delete a project and all associated pretest changes.
    """

    try:

        if not project_name:
            return False

        with _connection() as conn:

            try:

                # -------------------------------------------------------------
                # Find project
                # -------------------------------------------------------------

                project = conn.execute(
                    _prepare_sql(
                        """
                        SELECT project_id
                        FROM projects
                        WHERE project_name = ?
                        """
                    ),
                    (project_name,),
                ).fetchone()

                if not project:
                    return False

                project_id = project[0]

                # -------------------------------------------------------------
                # Delete child records explicitly.
                #
                # This keeps behavior consistent even if an existing database
                # was created without ON DELETE CASCADE.
                # -------------------------------------------------------------

                conn.execute(
                    _prepare_sql(
                        """
                        DELETE FROM pretest_changes
                        WHERE project_id = ?
                        """
                    ),
                    (project_id,),
                )

                # -------------------------------------------------------------
                # Delete project
                # -------------------------------------------------------------

                cursor = conn.execute(
                    _prepare_sql(
                        """
                        DELETE FROM projects
                        WHERE project_id = ?
                        """
                    ),
                    (project_id,),
                )

                conn.commit()

                return cursor.rowcount > 0

            except Exception as exc:

                conn.rollback()

                print(
                    f"❌ Database error deleting project: {exc}"
                )

                return False

    except Exception as exc:

        print(
            f"❌ Unexpected error in delete_project: {exc}"
        )

        return False
