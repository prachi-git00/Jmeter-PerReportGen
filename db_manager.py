# DATABASE INITIALIZATION
# =============================================================================

def init_database():
    """
    Initialize the database and required tables.

    This function intentionally does NOT silently fall back from PostgreSQL
    to SQLite. If PostgreSQL is configured but unavailable, the real error
    should be shown so deployment configuration can be fixed.
    """

    try:
        with _connection() as conn:
            _init_db_tables(conn)

    except Exception as exc:

        database_name = _database_name()

        raise RuntimeError(
            f"{database_name} database initialization failed: {exc}"
        ) from exc


def _init_db_tables(conn):
    """
    Create database tables and indexes.
    """

    cursor = conn.cursor()

    pk_sql = _primary_key_sql()

    # =========================================================================
    # PROJECTS TABLE
    # =========================================================================

    projects_sql = f"""
        CREATE TABLE IF NOT EXISTS projects (
            project_id {pk_sql},
            project_name TEXT UNIQUE NOT NULL,
            created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """

    cursor.execute(
        _prepare_sql(projects_sql)
    )

    # =========================================================================
    # PRETEST CHANGES TABLE
    # =========================================================================

    pretest_sql = f"""
        CREATE TABLE IF NOT EXISTS pretest_changes (
            change_id {pk_sql},
            project_id INTEGER NOT NULL,
            run_id TEXT NOT NULL,
            tier TEXT NOT NULL,
            changes TEXT NOT NULL,
            change_date DATE NOT NULL,
            created_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (project_id)
                REFERENCES projects(project_id)
                ON DELETE CASCADE
        )
    """

    cursor.execute(
        _prepare_sql(pretest_sql)
    )

    # Commit table creation before checking/altering columns.
    conn.commit()

    # =========================================================================
    # BACKWARD COMPATIBILITY
    # =========================================================================

    columns = _table_columns(conn)

    if "tier" not in columns:

        try:

            if _is_postgres_enabled():

                cursor.execute(
                    """
                    ALTER TABLE pretest_changes
                    ADD COLUMN tier TEXT DEFAULT ''
                    """
                )

            else:

                cursor.execute(
                    """
                    ALTER TABLE pretest_changes
                    ADD COLUMN tier TEXT DEFAULT ''
                    """
                )

            conn.commit()

        except Exception as exc:

            # It is possible another process created the column between
            # checking and altering it. Only ignore the specific situation
            # where the column already exists.
            if "already exists" not in str(exc).lower():
                conn.rollback()
                raise

    # =========================================================================
    # INDEXES
    # =========================================================================

    index_sql = """
        CREATE INDEX IF NOT EXISTS idx_pretest_changes_project_date
        ON pretest_changes (
            project_id,
            change_date DESC,
            created_timestamp DESC
        )
    """

    cursor.execute(
        _prepare_sql(index_sql)
    )

    # Useful index for project + Run ID lookups.
    run_index_sql = """
        CREATE INDEX IF NOT EXISTS idx_pretest_changes_project_run
        ON pretest_changes (
            project_id,
            run_id
        )
    """

    cursor.execute(
        _prepare_sql(run_index_sql)
    )

    conn.commit()


